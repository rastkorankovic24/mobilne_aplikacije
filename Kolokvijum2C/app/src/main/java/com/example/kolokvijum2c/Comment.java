package com.example.kolokvijum2c;

public class Comment {

    private int id;
    private int postId;
    private String name;
    private String email;
    private String body;

    public int getId() {
        return id;
    }

    public int getPostId() {
        return postId;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getBody() {
        return body;
    }
}
